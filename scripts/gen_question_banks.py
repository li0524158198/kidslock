def add(bank_key, q, opts, char=None, ans=0):
    """未指定 ans 时 opts[0] 为正确答案（客户端展示时打乱）；
    生成端做过 shuffle 的题必须显式传入 shuffle 后的正确答案索引"""
    banks.setdefault(bank_key, []).append(
        {"q": q, "opts": [o for o in opts], "ans": ans, "char": char})


